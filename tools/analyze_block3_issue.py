# Анализируем загрузки Навои
conn = sqlite3.connect(str(db_path))
conn.row_factory = sqlite3.Row
cursor = conn.cursor()

cursor.execute("""
    SELECT u.batch_id, u.filename, u.file_type, u.status, u.created_at
    FROM uploads u
    JOIN enterprises e ON u.enterprise_id = e.id
    WHERE e.name LIKE '%Navoiy%' OR e.name LIKE '%Навои%'
    ORDER BY u.created_at DESC
""")

navoiy_uploads = cursor.fetchall()
conn.close()

# Анализ типов файлов
file_types = {}
for row in navoiy_uploads:
    file_type = row['file_type'] or 'Unknown'
    if file_type not in file_types:
        file_types[file_type] = []
    file_types[file_type].append({
        "filename": row['filename'],
        "batch_id": row['batch_id']
    })

print("📊 АНАЛИЗ ЗАГРУЗОК НАВОИ:")
print("-" * 80)
print(f"Всего загрузок: {len(navoiy_uploads)}")
print()
print("Типы файлов:")
for file_type, files in file_types.items():
    print(f"  - {file_type}: {len(files)} файлов")
    for file in files[:3]:
        print(f"    • {file['filename']}")
    if len(files) > 3:
        print(f"    ... и ещё {len(files) - 3} файлов")
print()

